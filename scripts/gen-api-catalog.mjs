// Regenerates lib/api-catalog.ts — the GET routes GrokBot may read via the MCP `call_api` tool.
//   node scripts/gen-api-catalog.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1")), "..");
const apiDir = path.join(root, "app", "api");

// Login, user/access administration, bot plumbing and learner-token (LMS login) routes stay off call_api.
const SKIP = [/^\/api\/auth\b/, /^\/api\/admin\b/, /^\/api\/mcp\b/, /^\/api\/bot\b/, /^\/api\/lms\/auth\b/];
const LEARNER_ONLY = /requireLmsLearner|resolveLmsIdentity|getLmsSession|verifyLmsToken|lmsSession/;
const MANAGER_AUTH = /requireAuth|withAuth\(|requireLmsManager/;

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.name === "route.ts") out.push(full);
  }
  return out;
}

function describe(source) {
  const lines = source.split(/\r?\n/);
  const at = lines.findIndex((l) => /export\s+(async\s+)?function\s+GET\b|export\s+const\s+GET\b/.test(l));
  const notes = [];
  for (let i = at - 1; i >= 0 && i >= at - 12; i--) {
    const t = lines[i].trim();
    if (!t) { if (notes.length) break; continue; }
    if (!/^(\/\/|\/\*\*?|\*)/.test(t)) break;
    const text = t.replace(/^(\/\/+|\/\*\*?|\*\/?|\*)\s?/, "").replace(/\*\/$/, "").trim();
    if (text) notes.unshift(text);
  }
  return notes.join(" ").replace(/\s+/g, " ").slice(0, 300);
}

const entries = [];
for (const file of walk(apiDir)) {
  const source = fs.readFileSync(file, "utf8");
  if (!/export\s+(async\s+)?function\s+GET\b|export\s+const\s+GET\b|export\s*\{[^}]*\bGET\b/.test(source)) continue;
  const route = "/api/" + path.relative(apiDir, path.dirname(file)).split(path.sep).join("/");
  const apiPath = route.replace(/\/$/, "");
  if (SKIP.some((re) => re.test(apiPath))) continue;
  if (LEARNER_ONLY.test(source) && !MANAGER_AUTH.test(source)) continue;
  entries.push({ path: apiPath, description: describe(source) });
}
entries.sort((a, b) => a.path.localeCompare(b.path));

const body =
  "// Generated by scripts/gen-api-catalog.mjs — do not edit by hand.\n" +
  "export type ApiCatalogEntry = { path: string; description: string };\n\n" +
  "export const API_CATALOG: ApiCatalogEntry[] = " +
  JSON.stringify(entries, null, 2) +
  ";\n";
fs.writeFileSync(path.join(root, "lib", "api-catalog.ts"), body);
console.log(`Wrote ${entries.length} GET routes to lib/api-catalog.ts`);
